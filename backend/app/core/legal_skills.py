# ── 内置 + 用户自定义技能合并 ─────────────────
def get_all_skills(owner_user_id: int = 0) -> dict[str, dict]:
    """合并内置技能和用户自定义技能，按分类分组。"""
    from app.services.skill_service import list_user_skills as _list_db_skills

    result: dict[str, dict] = {}
    # 内置技能
    for name, info in LEGAL_SKILLS.items():
        cat = info["category"]
        if cat not in result:
            result[cat] = []
        result[cat].append({"name": name, "description": info["description"], "builtin": True})

    # 用户自定义技能
    db_skills = _list_db_skills(owner_user_id=owner_user_id)
    for s in db_skills:
        cat = s["category"]
        if cat not in result:
            result[cat] = []
        result[cat].append({"name": s["name"], "description": s["description"], "builtin": False})

    return result
